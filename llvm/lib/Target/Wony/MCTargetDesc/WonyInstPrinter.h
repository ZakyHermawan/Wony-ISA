#pragma once

#include "MCTargetDesc/WonyMCTargetDesc.h"
#include "llvm/ADT/StringRef.h"
#include "llvm/MC/MCInstPrinter.h"

#include <utility>

namespace llvm {

class WonyInstPrinter : public MCInstPrinter {
private:
  // Operand printer.
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImm(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printRegName(raw_ostream &OS, MCRegister Reg) override;

public:
  WonyInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                   const MCRegisterInfo &MRI);

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  /// Definition of these functions is auto generated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  virtual void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  virtual bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);
};

} // end namespace llvm
